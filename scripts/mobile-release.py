#!/usr/bin/env python3
"""Advance the shared iOS/Android release once per published update, Europe/Madrid."""
from pathlib import Path
from datetime import datetime
from zoneinfo import ZoneInfo
import json,re
root=Path(__file__).resolve().parents[1]
p=root/'mobile-release.json';old=json.loads(p.read_text());today=datetime.now(ZoneInfo('Europe/Madrid')).date().isoformat()
if old['date']>today:raise SystemExit('Release date is ahead of local calendar; refusing to go backwards')
revision=old['revision']+1 if old['date']==today else 1
label=today.replace('-','')+'.'+str(revision)
value={'date':today,'revision':revision,'version':label,'iosBuild':old['iosBuild']+1,'androidVersionCode':old['androidVersionCode']+1}
p.write_text(json.dumps(value,indent=2)+'\n')
project=root/'ios/Admirito/project.yml';text=project.read_text();text=re.sub(r"MARKETING_VERSION: '[^']+'","MARKETING_VERSION: '"+label+"'",text);text=re.sub(r"CURRENT_PROJECT_VERSION: '[^']+'","CURRENT_PROJECT_VERSION: '"+str(value['iosBuild'])+"'",text);project.write_text(text)
(root/'ios/Admirito/Sources/MobileRelease.swift').write_text('// Generated by scripts/mobile-release.py from mobile-release.json.\nenum MobileRelease { static let version = "'+label+'" }\n')
print(label)
